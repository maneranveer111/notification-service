import uuid
from datetime import datetime

from sqlalchemy import String, Text, DateTime, Integer, Index, ForeignKey, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models.api_client import ApiClient  # noqa: F401 - ensure referenced table is registered
from app.models.template import Template  # noqa: F401 - ensure referenced table is registered
from app.models.suppression import Suppression  # noqa: F401 - ensure suppression table is registered


class Notification(Base):
    """
    This class maps to a DB table.
    Each instance of Notification = one row in the notifications table.
    """

    __tablename__ = "notifications"

    __table_args__ = (
        Index("ix_notifications_status_created", "status", "created_at"),
        Index("ix_notifications_recipient", "recipient"),
        Index("ix_notifications_provider_message_id", "provider_message_id"),
        Index("ix_notifications_created_at", "created_at"),
        Index("ix_notifications_status_updated_at", "status", "updated_at"),
        Index("ix_notifications_status_scheduled_at", "status", "scheduled_at"),
        Index("ux_notifications_idempotency_key", "idempotency_key", unique=True),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    client_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("api_clients.id"),
        nullable=True,
        index=True,
    )
    template_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("templates.id"),
        nullable=True,
    )

    batch_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )

    category: Mapped[str] = mapped_column(String(20), nullable=False, default="transactional", server_default="transactional")

    channel: Mapped[str] = mapped_column(String(20), nullable=False)

    recipient: Mapped[str] = mapped_column(String(255), nullable=False)

    subject: Mapped[str | None] = mapped_column(String(255), nullable=True)
    body: Mapped[str | None] = mapped_column(Text, nullable=True)

    status: Mapped[str] = mapped_column(String(20), nullable=False, default="pending")
    priority: Mapped[str] = mapped_column(String(10), nullable=False, default="normal", server_default="normal")

    attempt_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    max_attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=3)

    provider: Mapped[str | None] = mapped_column(
        String(50), nullable=True
    )  # "sendgrid" / "twilio" / "brevo" / "smtp"
    provider_message_id: Mapped[str | None] = mapped_column(String(255), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    idempotency_key: Mapped[str | None] = mapped_column(String(255), nullable=True)
    request_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)

    delivered_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    sent_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    scheduled_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),  # generated by DB
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),  
    )
